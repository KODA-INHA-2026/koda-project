import {test,expect} from '@playwright/test';
import {authenticate,logout} from './helpers.js';
import {testOrigin} from '../../scripts/test-environment.js';

test('S06: only the current request is highlighted; record failure retains the document',async({page})=>{
 test.setTimeout(90000);
 const evidence='/evidence/KODA-PRD-20260930-GAON/versions/1';
 await page.goto('/');await authenticate(page,'finance-a');
 const finance=await(await page.request.get('/api/me')).json();
 const people=await(await page.request.get('/api/finance/accountants')).json();
 const internal=await page.request.post('/api/finance'+evidence+'/internal-grants',{headers:{origin:testOrigin,'x-csrf-token':finance.csrf},data:{recipientDid:people[0].did,expiresAt:new Date(Date.now()+3600000).toISOString(),idempotencyKey:crypto.randomUUID()}});
 expect(internal.status()).toBe(201);
 await logout(page);await authenticate(page,'accounting-a');
 const accounting=await(await page.request.get('/api/me')).json();
 const auditors=await(await page.request.get('/api/accounting/auditors')).json();
 const external=await page.request.post('/api'+evidence+'/grants',{headers:{origin:testOrigin,'x-csrf-token':accounting.csrf},data:{auditorDid:auditors[0].did,idempotencyKey:crypto.randomUUID()}});
 expect(external.status()).toBe(201);const created=await external.json();
 await logout(page);await page.goto('/share#token='+created.token);await authenticate(page,'auditor-b');
 await expect(page.locator('.certificate')).toBeVisible();
 const before=await page.locator('.certificate').innerText();
 const record=page.locator('.trace-graph li').filter({hasText:'모의 체인 · 발행 기록 조회'});
 const cryptography=page.locator('.trace-graph li').filter({hasText:'브라우저 · DID 서명과 지문 대조'});
 let release!:()=>void,reached!:()=>void;
 const held=new Promise<void>(r=>release=r),started=new Promise<void>(r=>reached=r);
 await page.route('**/anchor-record',async route=>{reached();await held;await route.continue().catch(()=>{});});
 await page.getByRole('button',{name:'원본 검증하기',exact:true}).click();await started;
 await expect(page.locator('.trace-graph [data-state=running]')).toHaveCount(1);
 await expect(record).toHaveAttribute('data-state','running');await expect(cryptography).toHaveAttribute('data-state','idle');
 await expect(page.getByRole('button',{name:'검사 중…',exact:true})).toBeDisabled();
 release();await page.unroute('**/anchor-record');await expect(page.locator('.pdf-result')).toContainText('KODA가 발행한 원본과 같습니다.');
 expect(await page.locator('.certificate').innerText()).toBe(before);
 const cdp=await page.context().newCDPSession(page);await cdp.send('DOM.enable');await cdp.send('CSS.enable');
 const {root}=await cdp.send('DOM.getDocument');const {nodeId}=await cdp.send('DOM.querySelector',{nodeId:root.nodeId,selector:'.scene-title h1'});
 const fonts=await cdp.send('CSS.getPlatformFontsForNode',{nodeId});expect(fonts.fonts.some((f:{isCustomFont:boolean;familyName:string;glyphCount:number})=>f.isCustomFont&&f.familyName.includes('Pretendard')&&f.glyphCount>0)).toBe(true);
 await page.route('**/anchor-record',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:'RECORD_UNAVAILABLE',message:'모의 기록 조회 실패'})}));
 await page.getByRole('button',{name:'원본 검증하기',exact:true}).focus();await page.keyboard.press('Enter');
 await expect(page.locator('.pdf-result')).toContainText('모의 기록을 확인할 수 없습니다');await expect(record).toHaveAttribute('data-state','blocked');
 expect(await page.locator('.certificate').innerText()).toBe(before);
});
