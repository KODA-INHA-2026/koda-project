import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const url = process.env.KODA_CHECK_URL ?? 'http://127.0.0.1:5190/live.html?view=verify';
const output = resolve('docs/design/five-stage-2026-11-07/signed-comparison');
const checkName = ['127.0.0.1', 'localhost'].includes(new URL(url).hostname) ? 'browser' : 'public';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [], checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(url);
  const verifyButton = page.getByRole('button', { name: '문서 검증하기', exact: true });
  const waitForLoadedPair = async () => {
    await expect(page.locator('.ve-file-row.is-loaded')).toHaveCount(2);
    await expect(verifyButton).toBeEnabled();
  };
  await expect(page.getByRole('button', { name: '발급 원본 100 BTC', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: /다시 서명한 문서/ })).toBeEnabled();
  await expect(page.locator('.ve-local-checks')).toHaveCount(0);
  await page.screenshot({ path: `${output}/04-ready.png`, fullPage: true });
  checks.push('Approved signed comparison is selectable, with no precomputed verdict');
  await page.getByRole('button', { name: '발급 원본 100 BTC', exact: true }).click();
  await waitForLoadedPair();
  await verifyButton.click();
  await expect(page.locator('.ve-outcome')).toHaveClass(/is-match/, { timeout: 120000 });
  await expect(page.locator('.ve-questions .is-confirmed')).toHaveCount(3);
  await expect(page.locator('.ve-route-label.is-observed')).toHaveCount(2);
  checks.push('Original matches after actual RPC and both observed request/response paths remain');
  await page.screenshot({ path: `${output}/04-original.png`, fullPage: true });
  await page.getByRole('button', { name: 'PDF만 변경 120 BTC', exact: true }).click();
  await expect(page.locator('.ve-outcome')).toHaveCount(0);
  await waitForLoadedPair();
  await verifyButton.click();
  await expect(page.locator('.ve-outcome')).toHaveClass(/is-mismatch/, { timeout: 120000 });
  await expect(page.locator('.ve-questions .is-confirmed')).toHaveCount(0);
  checks.push('PDF-only change still fails and preserves its distinct signature meaning');
  await page.screenshot({ path: `${output}/04-altered.png`, fullPage: true });
  await page.getByRole('button', { name: /다시 서명한 문서/ }).click();
  await expect(page.locator('.ve-outcome')).toHaveCount(0);
  await expect(page.locator('.ve-local-checks .is-confirmed')).toHaveCount(0);
  await waitForLoadedPair();
  await verifyButton.click();
  await expect(page.locator('.ve-experience')).toHaveAttribute('data-motion-step', 'compare', { timeout: 120000 });
  await page.getByRole('button', { name: '처리 흐름 일시정지', exact: true }).click();
  await expect(page.locator('.ve-local-checks .is-confirmed')).toHaveCount(2);
  await expect(page.locator('.ve-file-digest')).toContainText('0x42c75760');
  await expect(page.locator('.ve-return-slot')).toContainText('0xba9bca0b');
  await expect(page.locator('.ve-route-label.is-observed')).toHaveCount(2);
  await page.screenshot({ path: `${output}/04-signed-compare.png`, fullPage: true });
  await page.getByRole('button', { name: /결과 바로 보기/ }).click();
  await expect(page.locator('.ve-outcome h2')).toHaveText('서명은 유효하지만 등록 원본과 다릅니다');
  await expect(page.locator('.ve-questions .is-confirmed')).toHaveCount(1);
  await expect(page.locator('.ve-questions .is-warning')).toHaveCount(2);
  await page.screenshot({ path: `${output}/04-signed-result.png`, fullPage: true });
  checks.push('Genuine user-approved signature + PDF match, actual finalized registered hash differs; paused paths and distinct verdict verified');
  for (const act of [0, 1, 2, 4, 3]) await page.locator('.kp-acts button').nth(act).click();
  await expect(page.locator('.ve-file-row.is-loaded')).toHaveCount(2);
  await expect(page.locator('.ve-outcome h2')).toHaveText('서명은 유효하지만 등록 원본과 다릅니다');
  checks.push('All five scene transitions preserve the selected files and completed comparison result');
  await page.getByRole('button', { name: '다시 선택', exact: true }).click();
  const input = page.getByLabel('전달받은 PDF와 검증정보 선택');
  await input.setInputFiles('docs/portfolio/2026-11-06-sepolia/inha-20261106/inha-altered-120-btc.pdf');
  await expect(page.locator('.ve-file-row').first()).toContainText('inha-altered-120-btc.pdf');
  await expect(page.locator('.ve-input-status')).toContainText('수신자가 선택한 파일');
  await input.setInputFiles('docs/portfolio/2026-11-07-signed-comparison/signed-comparison.json');
  await expect(page.locator('.ve-input-status')).toContainText('수신자가 선택한 파일');
  await waitForLoadedPair();
  await verifyButton.click();
  await expect(page.locator('.ve-outcome h2')).toHaveText('서명은 유효하지만 등록 원본과 다릅니다', { timeout: 120000 });
  checks.push('Downloaded comparison JSON and PDF can be received separately and freshly verified without wallet');
  await page.getByText('발표자 실행 준비', { exact: true }).click();
  await expect(page.getByRole('button', { name: '비교용 120 BTC 문서에 서명', exact: true })).toBeDisabled();
  await expect(page.locator('.signed-comparison-setup')).toContainText('새 거래와 가스비는 없습니다');
  await page.locator('.signed-comparison-setup').screenshot({ path: `${output}/presenter-prepare.png` });
  checks.push('Signing is explicit and presenter-only, disabled without a wallet');
  await page.getByText('발표자 실행 준비', { exact: true }).click();
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `${output}/04-${width}.png`, fullPage: true });
  }
  checks.push('1280px and 390px have no page overflow');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.route('https://ethereum-sepolia-rpc.publicnode.com/**', route => route.abort());
  await page.getByRole('button', { name: /다시 검증하기/ }).click();
  await expect(page.locator('.ve-outcome')).toHaveClass(/is-failure/, { timeout: 45000 });
  await expect(page.locator('.ve-route-label.is-observed')).toHaveCount(0);
  await expect(page.locator('.ve-registration-value')).toHaveCount(0);
  checks.push('RPC failure cannot retain a previous conflict verdict or fabricate returned record');
  await page.locator('.kp-acts button').nth(0).click();
  await expect(page.getByRole('heading', { name: 'KODA의 수탁정보로 잔고 증명서를 만듭니다' })).toBeVisible();
  await page.locator('.kp-acts button').nth(2).click();
  await expect(page.getByRole('button', { name: 'PDF 받기', exact: true })).toBeEnabled();
  await page.locator('.kp-acts button').nth(4).click();
  await expect(page.locator('.ev-verdict')).toHaveClass(/is-match/);
  checks.push('01 issuance and 05 saved external result remain available');
  expect(errors).toEqual([]);
  await writeFile(`${output}/${checkName}-check.json`, JSON.stringify({ at: new Date().toISOString(), url, checks, errors, realComparisonSignature: 'user-approved, verified against finalized Sepolia registration' }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} finally { await browser.close(); }
